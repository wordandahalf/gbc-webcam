void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  switch (GPIO_Pin) {
    case PIN_READ_BLUE:
      if (HAL_ADC_Start_DMA(&hadc1, (uint32_t*) adc_buffer, 128 * 128) != HAL_OK) {
        Error_Handler();
      }
      BSP_LED_Toggle(LED_GREEN);
      break;
    default:
      break;
  }
}

